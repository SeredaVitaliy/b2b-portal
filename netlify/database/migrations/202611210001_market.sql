CREATE TABLE companies (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE, kind text NOT NULL CHECK (kind IN ('buyer','supplier')),
 active boolean NOT NULL DEFAULT true, minimum integer NOT NULL DEFAULT 500 CHECK(minimum>=0),
 lead_days integer NOT NULL DEFAULT 1 CHECK(lead_days BETWEEN 1 AND 14)
);
CREATE TABLE categories (id integer PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE products (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL,
 category integer NOT NULL REFERENCES categories, unit text NOT NULL, approved boolean NOT NULL DEFAULT false,
 submitted_by integer REFERENCES companies);
CREATE TABLE offers (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product integer NOT NULL REFERENCES products,
 supplier integer NOT NULL REFERENCES companies, price integer NOT NULL CHECK(price>0), stock integer NOT NULL CHECK(stock>=0),
 pack integer NOT NULL DEFAULT 1 CHECK(pack>0), UNIQUE(product,supplier));
CREATE TABLE sessions (token text PRIMARY KEY, role text NOT NULL, company integer REFERENCES companies,
 expires timestamptz NOT NULL DEFAULT now()+interval '4 hours');
CREATE TABLE checkouts (id uuid PRIMARY KEY, buyer integer NOT NULL REFERENCES companies);
CREATE TABLE orders (id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY, checkout uuid REFERENCES checkouts,
 buyer integer NOT NULL REFERENCES companies, supplier integer NOT NULL REFERENCES companies, address text NOT NULL,
 delivery date NOT NULL, note text NOT NULL, status text NOT NULL DEFAULT 'new', created timestamptz DEFAULT now());
CREATE TABLE order_items (order_id integer REFERENCES orders, offer integer REFERENCES offers, name text NOT NULL,
 price integer NOT NULL, quantity integer NOT NULL, PRIMARY KEY(order_id,offer));
CREATE TABLE order_events (order_id integer REFERENCES orders, status text NOT NULL, created timestamptz DEFAULT now());
CREATE INDEX orders_buyer ON orders(buyer,id DESC);
CREATE INDEX orders_supplier ON orders(supplier,id DESC);
